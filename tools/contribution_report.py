"""Summarise who changed what, straight from the git history.

    python tools/contribution_report.py            # writes CONTRIBUTIONS_LOG.md
    python tools/contribution_report.py --since 2026-11-18

Run it just before submission and commit the result. Every line comes from `git log`, so it can be
checked by anyone with the repository (GitHub's Insights -> Contributors page shows the same data).
"""
import argparse, collections, json, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SEP = "\x1f"


def git_log(since=None):
    fmt = f"--format=@@{SEP}%h{SEP}%an{SEP}%ae{SEP}%ad{SEP}%s"
    cmd = ["git", "-C", str(ROOT), "log", "--no-merges", "--numstat", "--date=short", fmt]
    if since:
        cmd.append(f"--since={since}")
    out = subprocess.run(cmd, capture_output=True, text=True, check=True).stdout
    commits, cur = [], None
    for line in out.splitlines():
        if line.startswith("@@" + SEP):
            _, h, name, email, date, subject = line.split(SEP, 5)
            cur = {"hash": h, "name": name, "email": email, "date": date, "subject": subject, "files": []}
            commits.append(cur)
        elif line.strip() and cur is not None:
            added, removed, path = line.split("\t", 2)
            cur["files"].append((path, int(added) if added.isdigit() else 0, int(removed) if removed.isdigit() else 0))
    return commits


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--since", help="only count commits after this date (YYYY-MM-DD)")
    ap.add_argument("--out", default="CONTRIBUTIONS_LOG.md")
    args = ap.parse_args()

    team = json.loads((ROOT / "team.json").read_text())
    stage_lead = {f"stages/{k}.py": team["members"][v]["name"] for k, v in team["stages"].items()}
    by_author, baseline = collections.OrderedDict(), []
    for c in reversed(git_log(args.since)):                      # oldest first
        if c["subject"].lower().startswith("baseline"):
            baseline.append(c)                                   # shared starting draft, reported separately
        else:
            by_author.setdefault(c["name"], []).append(c)

    lines = ["# Contribution log (generated from git history)", "",
             f"Generated by `tools/contribution_report.py`{' since ' + args.since if args.since else ''}. "
             "Merge commits are excluded, and commits whose message starts with `Baseline` are listed separately. Line counts include generated files (the notebook), so read them together with the file list.", "",
             "## Summary", "",
             "| Author | Commits | Lines added | Lines removed | Stage files changed |",
             "|---|---:|---:|---:|---|"]
    for name, cs in by_author.items():
        add = sum(a for c in cs for _, a, _ in c["files"])
        rem = sum(r for c in cs for _, _, r in c["files"])
        stages = sorted({p.split("/")[-1] for c in cs for p, _, _ in c["files"] if p.startswith("stages/")})
        lines.append(f"| {name} | {len(cs)} | {add} | {rem} | {', '.join(stages) or '-'} |")

    lines += ["", "## Stage files: who changed each one", "", "| Stage file | Stage lead | Authors who changed it (commits) |", "|---|---|---|"]
    for path, lead in sorted(stage_lead.items()):
        counts = collections.Counter(c["name"] for cs in by_author.values() for c in cs if any(p == path for p, _, _ in c["files"]))
        lines.append(f"| `{path}` | {lead} | {', '.join(f'{n} ({k})' for n, k in counts.most_common()) or '-'} |")

    if baseline:
        lines += ["", "## Baseline (shared starting draft, not counted above)", ""]
        lines += [f"- `{c['hash']}` {c['date']} by {c['name']}: {c['subject']}" for c in baseline]

    lines += ["", "## Commits by author", ""]
    for name, cs in by_author.items():
        lines += [f"### {name}", "", "| Date | Commit | Message | Files |", "|---|---|---|---|"]
        for c in cs:
            files = ", ".join(f"`{p}`" for p, _, _ in c["files"][:6]) + (" …" if len(c["files"]) > 6 else "")
            subject = c["subject"].replace("|", "\\|")
            lines.append(f"| {c['date']} | `{c['hash']}` | {subject} | {files} |")
        lines.append("")

    (ROOT / args.out).write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out}: {sum(len(v) for v in by_author.values())} commits by {len(by_author)} authors")


if __name__ == "__main__":
    main()
